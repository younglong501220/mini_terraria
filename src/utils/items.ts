export function createItem(id: string, count: number = 1): ItemDef {
  const template = ITEM_CATALOG[id];
  if (!template) {
    return {
      id,
      name: id,
      type: 'material',
      icon: '📦',
      desc: '',
      count,
      maxStack: 99,
      rarity: 'white',
    };
  }
  return {
    ...template,
    count,
  };
}

